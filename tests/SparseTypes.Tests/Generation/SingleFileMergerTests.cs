using System.Collections.Immutable;
using SparseTypes.Generator;
using SparseTypes.Generator.Shared;

namespace SparseTypes.Tests;

/// <summary>Single-file merger output mechanics.</summary>
/// <remarks>
/// Locks byte-for-byte output while the merger avoids per-line body
/// allocations: header order, CRLF/LF behavior, blank lines and
/// final-newline rules.
/// </remarks>
public sealed class SingleFileMergerTests
{
    private static string Nl => Environment.NewLine;

    private static ImmutableArray<SparseGeneratedSource> Additional(params string[] sources) =>
        sources
            .Select(static source => new SparseGeneratedSource("Extra", source))
            .ToImmutableArray();

    [Test]
    public void NoAdditionalReturnsSurfaceUnchanged()
    {
        const string surface = "// generated\nnamespace Demo {\n}\n";

        SparseTypesSingleFileMerger.Merge(surface, default).ShouldBe(surface);
        SparseTypesSingleFileMerger
            .Merge(surface, ImmutableArray<SparseGeneratedSource>.Empty)
            .ShouldBe(surface);
    }

    [Test]
    public void BasicMergeHoistsOnlyNewUsingsAndPragmas()
    {
        const string surface =
            "// <auto-generated/>\n#nullable enable\nusing System;\nnamespace Demo {\n    // surface body\n}\n";
        const string extra =
            "// <auto-generated/>\n#nullable enable\nusing System;\nusing System.Collections.Generic;\n#pragma warning disable CS1591\nnamespace Demo {\n    // extra body\n}\n";

        var merged = SparseTypesSingleFileMerger.Merge(surface, Additional(extra));

        merged.ShouldBe(
            "// <auto-generated/>\n#nullable enable\nusing System;\n"
                + "using System.Collections.Generic;"
                + Nl
                + "#pragma warning disable CS1591"
                + Nl
                + "namespace Demo {\n    // surface body\n}\n"
                + Nl
                + "namespace Demo {\n    // extra body\n}\n"
        );
    }

    [Test]
    public void DuplicateUsingsAcrossFilesHoistOnce()
    {
        const string surface = "using System;\nnamespace Demo {\n    // surface\n}\n";
        const string first =
            "using System;\nusing System.Linq;\nnamespace Demo {\n    // first\n}\n";
        const string second =
            "using System.Linq;\nusing System.Text;\nnamespace Demo {\n    // second\n}\n";

        var merged = SparseTypesSingleFileMerger.Merge(surface, Additional(first, second));

        merged.ShouldBe(
            "using System;\n"
                + "using System.Linq;"
                + Nl
                + "using System.Text;"
                + Nl
                + "namespace Demo {\n    // surface\n}\n"
                + Nl
                + "namespace Demo {\n    // first\n}\n"
                + Nl
                + "namespace Demo {\n    // second\n}\n"
        );
    }

    [Test]
    public void CrlfLineEndingsPreservedInHeaderAndBodies()
    {
        const string surface =
            "// generated\r\n#nullable enable\r\nusing System;\r\nnamespace Demo {\r\n    // surface\r\n}\r\n";
        const string extra =
            "// generated\r\nusing System;\r\nusing System.IO;\r\nnamespace Demo {\r\n    // extra\r\n}\r\n";

        var merged = SparseTypesSingleFileMerger.Merge(surface, Additional(extra));

        merged.ShouldBe(
            "// generated\r\n#nullable enable\r\nusing System;\r\n"
                + "using System.IO;"
                + Nl
                + "namespace Demo {\r\n    // surface\r\n}\r\n"
                + Nl
                + "namespace Demo {\r\n    // extra\r\n}\r\n"
        );
    }

    [Test]
    public void HeaderlessSourcesJoinWithBlankSeparators()
    {
        const string surface = "namespace A {}\n";
        const string extra = "namespace B {}\n";

        var merged = SparseTypesSingleFileMerger.Merge(surface, Additional(extra));

        merged.ShouldBe("namespace A {}\n" + Nl + "namespace B {}\n");
    }

    [Test]
    public void MissingTrailingNewlinesGainExactlyOneSeparator()
    {
        const string surface = "using System;\nnamespace A {}";
        const string extra = "using System.Text;\nnamespace B {}";

        var merged = SparseTypesSingleFileMerger.Merge(surface, Additional(extra));

        merged.ShouldBe(
            "using System;\n"
                + "using System.Text;"
                + Nl
                + "namespace A {}"
                + Nl
                + Nl
                + "namespace B {}"
                + Nl
        );
    }

    [Test]
    public void EmptySurfaceKeepsLegacyBlankHeader()
    {
        const string extra = "using System;\nnamespace B {}\n";

        var merged = SparseTypesSingleFileMerger.Merge(string.Empty, Additional(extra));

        merged.ShouldBe("\nusing System;" + Nl + Nl + Nl + "namespace B {}\n");
    }

    [Test]
    public void SurfaceWithoutBodyKeepsHeaderAndAppendsBodies()
    {
        const string surface = "// generated\nusing System;\n";
        const string extra = "using System;\nnamespace B {}\n";

        var merged = SparseTypesSingleFileMerger.Merge(surface, Additional(extra));

        merged.ShouldBe("// generated\nusing System;\n" + Nl + Nl + "namespace B {}\n");
    }

    [Test]
    public void CommentOnlyExtraHeadersHoistNothing()
    {
        const string surface = "using System;\nnamespace A {}\n";
        const string extra = "// extra header\n#nullable enable\nnamespace B {}\n";

        var merged = SparseTypesSingleFileMerger.Merge(surface, Additional(extra));

        merged.ShouldBe("using System;\n" + "namespace A {}\n" + Nl + "namespace B {}\n");
    }

    [Test]
    public void LargeBodyRoundTripsWithoutReconstruction()
    {
        var bodyLine = "    // representative generated body line with fixed length\n";
        var bigBody =
            "namespace Demo {\n" + string.Concat(Enumerable.Repeat(bodyLine, 1000)) + "}\n";
        var surface = "// generated\nusing System;\n" + bigBody;

        var merged = SparseTypesSingleFileMerger.Merge(surface, Additional(bigBody, bigBody));

        merged.ShouldContain(bigBody);
        merged.ShouldBe("// generated\nusing System;\n" + bigBody + Nl + bigBody + Nl + bigBody);
    }
}
