    /// <inheritdoc />
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var analyzed = context
            .SyntaxProvider.ForAttributeWithMetadataName(
                ModelAttributeName,
                static (node, _) => node is TypeDeclarationSyntax,
                static (attributeContext, cancellationToken) =>
                    SparseModelAnalyzer.Analyze(
                        (INamedTypeSymbol)attributeContext.TargetSymbol,
                        Configuration,
                        cancellationToken
                    )
            )
            .WithTrackingName("SparseFragmentsGenerator.Analysis");
        var bclSetSupport = context
            .CompilationProvider.Select(
                static (compilation, _) =>
                    (
                        ReadOnlySet: SparseCollectionAnalyzer.HashSetImplementsReadOnlySet(
                            compilation
                        ),
                        Capacity: SparseCollectionAnalyzer.HashSetSupportsCapacity(compilation)
                    )
            )
            .WithComparer(EqualityComparer<(bool ReadOnlySet, bool Capacity)>.Default)
            .WithTrackingName("SparseFragmentsGenerator.BclSetSupport");
        var generated = analyzed
            .Combine(bclSetSupport)
            .Select(
                static (input, cancellationToken) =>
                    Render(
                        input.Left,
                        input.Right.ReadOnlySet,
                        input.Right.Capacity,
                        cancellationToken
                    )
            )
            .WithTrackingName("SparseFragmentsGenerator.Output");

        context.RegisterSourceOutput(
            generated,
            static (productionContext, result) => Emit(productionContext, result)
        );

        var promotedPerRoot = analyzed
            .Select(static (analysis, _) => analysis.PromotedModels)
            .WithTrackingName("SparseFragmentsGenerator.PromotedPerRoot");
        var promotedContributions = promotedPerRoot
            .SelectMany(
                static (models, _) =>
                    models.IsDefault ? ImmutableArray<SparsePromotedModel>.Empty : models
            )
            .WithTrackingName("SparseFragmentsGenerator.PromotedContributions");
        var explicitRootNames = analyzed
            .Select(static (analysis, _) => analysis.Model?.ModelTypeName)
            .Where(static name => name is not null)
            .Select(static (name, _) => name!)
            .WithTrackingName("SparseFragmentsGenerator.ExplicitRoots")
            .Collect();
        var promotedDedup = promotedContributions
            .Collect()
            .Combine(explicitRootNames)
            .Select(
                static (input, cancellationToken) =>
                    SparsePromotedAggregation.Deduplicate(
                        input.Left,
                        input.Right,
                        cancellationToken
                    )
            )
            .WithTrackingName("SparseFragmentsGenerator.PromotedDedup");
        var distinctPromoted = promotedDedup
            .SelectMany(static (result, _) => result.Distinct)
            .WithTrackingName("SparseFragmentsGenerator.PromotedDistinct");
        var promotedSources = distinctPromoted
            .Combine(bclSetSupport)
            .Select(
                static (input, cancellationToken) =>
                    RenderSinglePromoted(
                        input.Left,
                        input.Right.ReadOnlySet,
                        input.Right.Capacity,
                        cancellationToken
                    )
            )
            .WithTrackingName("SparseFragmentsGenerator.Promoted");
        context.RegisterSourceOutput(
            promotedSources,
            static (productionContext, result) => Emit(productionContext, result)
        );
        var promotedConflicts = promotedDedup
            .SelectMany(static (result, _) => result.Incompatible)
            .Select(
                static (entry, _) =>
                    new SparseGenerationResult(
                        null,
                        null,
                        ImmutableArray.Create(
                            new SparseGeneratorDiagnostic(
                                SparseFragmentsDiagnosticIds.IncompatiblePromotedModel,
                                null,
                                entry.DisplayName
                            )
                        )
                    )
            )
            .WithTrackingName("SparseFragmentsGenerator.PromotedConflicts");
        context.RegisterSourceOutput(
            promotedConflicts,
            static (productionContext, result) => Emit(productionContext, result)
        );

        var hasModels = analyzed
            .Select(static (analysis, _) => analysis.Model.HasValue)
            .Collect()
            .Select(static (presence, _) => presence.Any(static value => value))
            .WithComparer(EqualityComparer<bool>.Default);
        var generatedOncePlan = analyzed
            .Collect()
            .Combine(promotedDedup)
            .Combine(bclSetSupport)
            .Select(
                static (input, cancellationToken) =>
                    SparseGeneratedCapabilityPlanner.Aggregate(
                        input.Left.Left,
                        input.Left.Right.Distinct,
                        Configuration.EffectiveEmissionFeatures,
                        input.Right.ReadOnlySet,
                        input.Right.Capacity,
                        cancellationToken
                    )
            )
            .WithComparer(EqualityComparer<SparseGeneratedOncePlan>.Default)
            .WithTrackingName("SparseFragmentsGenerator.GeneratedOncePlan");
        var generatedOnceErrors = generatedOncePlan
            .Select(
                static (plan, _) =>
                    SparseGeneratedCapabilityPlanner.Validate(
                        plan,
                        Configuration.EffectiveEmissionFeatures
                    )
            )
            .WithComparer(EqualityComparer<ImmutableArray<string>>.Default)
            .WithTrackingName("SparseFragmentsGenerator.GeneratedOnceValidation");
        context.RegisterSourceOutput(
            generatedOnceErrors,
            static (productionContext, errors) =>
            {
                foreach (var message in errors)
                {
                    productionContext.ReportDiagnostic(
                        Diagnostic.Create(InvalidEmissionPlan, Location.None, message)
                    );
                }
            }
        );
        var needsEditSession = generatedOncePlan
            .Select(static (plan, _) => plan.Has(SparseGeneratedCapability.EditSession))
            .WithComparer(EqualityComparer<bool>.Default)
            .WithTrackingName("SparseFragmentsGenerator.GeneratedOnceEditSession");
        context.RegisterSourceOutput(
            needsEditSession,
            static (productionContext, emit) =>
            {
                if (emit)
                    SparseEditSessionEmitter.EmitCore(productionContext, Configuration);
            }
        );
        // Generated-Once shared helpers (adapters, clone kernels, removal
        // index): the track-2 capability plane is the single wiring. It won
        // over the track-3 manual aggregation (explicit/promoted
        // SparseGeneratedOnceRequirements union): the manual block is deleted
        // so only one kernel family is ever emitted, with the track-3
        // identities (SparseGeneratedOnceNames: CloneKernels, ReadOnlyAdapters,
        // RemovalIndex hint/type names). The plane adds prerequisite
        // validation (InvalidEmissionPlan) on top of the track-4
        // SparseEditSessionCapabilities validation that still runs inside
        // EmitCore, and the d7011db BCL set probe stays threaded through the
        // plan (portable set view) and the per-model renderers. Hint schemes
        // do not collide: edit-session cores use the EditSessionDialect
        // CoreHintName pair, patch operation kernels keep their own stable
        // hint (unwired seam), and these families use <ns>.*.g.cs.
        var clonePlan = generatedOncePlan
            .Select(
                static (plan, _) =>
                    (
                        Needed: plan.Has(SparseGeneratedCapability.CloneKernels),
                        Portable: plan.NeedsPortableSetView,
                        Capacity: plan.HashSetSupportsCapacity
                    )
            )
            .WithComparer(EqualityComparer<(bool Needed, bool Portable, bool Capacity)>.Default)
            .WithTrackingName("SparseFragmentsGenerator.GeneratedOnceCloneKernels");
        context.RegisterSourceOutput(
            clonePlan,
            static (productionContext, plan) =>
            {
                var implementationNamespace = SparseGeneratedOnceEmitter.TryGetNamespace(
                    Configuration
                );
                if (plan.Needed && implementationNamespace is not null)
                    productionContext.AddSource(
                        SparseGeneratedOnceEmitter.CloneKernelsHintName(implementationNamespace),
                        SourceText.From(
                            SparseGeneratedOnceEmitter.RenderCloneKernels(
                                implementationNamespace,
                                plan.Portable,
                                plan.Capacity,
                                productionContext.CancellationToken
                            ),
                            Encoding.UTF8
                        )
                    );
            }
        );
        var needsReadOnlyAdapters = generatedOncePlan
            .Select(static (plan, _) => plan.Has(SparseGeneratedCapability.ReadOnlyAdapters))
            .WithComparer(EqualityComparer<bool>.Default)
            .WithTrackingName("SparseFragmentsGenerator.GeneratedOnceReadOnlyAdapters");
        context.RegisterSourceOutput(
            needsReadOnlyAdapters,
            static (productionContext, emit) =>
            {
                var implementationNamespace = SparseGeneratedOnceEmitter.TryGetNamespace(
                    Configuration
                );
                if (emit && implementationNamespace is not null)
                    productionContext.AddSource(
                        SparseGeneratedOnceEmitter.ReadOnlyAdaptersHintName(
                            implementationNamespace
                        ),
                        SourceText.From(
                            SparseGeneratedOnceEmitter.RenderReadOnlyAdapters(
                                implementationNamespace,
                                productionContext.CancellationToken
                            ),
                            Encoding.UTF8
                        )
                    );
            }
        );
        var needsRemovalIndex = generatedOncePlan
            .Select(static (plan, _) => plan.Has(SparseGeneratedCapability.RemovalIndex))
            .WithComparer(EqualityComparer<bool>.Default)
            .WithTrackingName("SparseFragmentsGenerator.GeneratedOnceRemovalIndex");
        context.RegisterSourceOutput(
            needsRemovalIndex,
            static (productionContext, emit) =>
            {
                var implementationNamespace = SparseGeneratedOnceEmitter.TryGetNamespace(
                    Configuration
                );
                if (emit && implementationNamespace is not null)
                    productionContext.AddSource(
                        SparseGeneratedOnceEmitter.RemovalIndexHintName(implementationNamespace),
                        SourceText.From(
                            SparseGeneratedOnceEmitter.RenderRemovalIndex(
                                implementationNamespace,
                                productionContext.CancellationToken
                            ),
                            Encoding.UTF8
                        )
                    );
            }
        );
        var shouldEmitIsExternalInit = context
            .CompilationProvider.Combine(context.AnalyzerConfigOptionsProvider)
            .Combine(hasModels)
            .Select(
                static (input, _) =>
                {
                    var ((compilation, options), anyModels) = input;
                    return anyModels
                        && ShouldEmitIsExternalInit(
                            compilation,
                            IsExternalInitEmissionEnabled(options)
                        );
                }
            )
            .WithComparer(EqualityComparer<bool>.Default)
            .WithTrackingName("SparseFragmentsGenerator.IsExternalInit");
        context.RegisterSourceOutput(
            shouldEmitIsExternalInit,
            static (productionContext, emit) =>
            {
                if (emit)
                    productionContext.AddSource(
                        IsExternalInitHintName,
                        SourceText.From(IsExternalInitSource, Encoding.UTF8)
                    );
            }
        );
        var shouldEmitNotNullWhen = context
            .CompilationProvider.Combine(hasModels)
            .Select(
                static (input, _) =>
                    input.Right
                    && input.Left.GetTypeByMetadataName(NotNullWhenAttributeName) is null
            )
            .WithComparer(EqualityComparer<bool>.Default)
            .WithTrackingName("SparseFragmentsGenerator.NotNullWhen");
        context.RegisterSourceOutput(
            shouldEmitNotNullWhen,
            static (productionContext, emit) =>
            {
                if (emit)
                    productionContext.AddSource(
                        NotNullWhenHintName,
                        SourceText.From(NotNullWhenSource, Encoding.UTF8)
                    );
            }
        );
    }

    private static bool IsExternalInitEmissionEnabled(AnalyzerConfigOptionsProvider options) =>
        !options.GlobalOptions.TryGetValue(EmitIsExternalInitOption, out var value)
        || !string.Equals(value, "false", StringComparison.OrdinalIgnoreCase);

    private static bool ShouldEmitIsExternalInit(Compilation compilation, bool configured) =>
        SparseExternalInit.ShouldEmitIsExternalInit(compilation, configured);

    private static void Emit(SourceProductionContext context, SparseGenerationResult result)
    {
        context.CancellationToken.ThrowIfCancellationRequested();
        foreach (var diagnostic in result.Diagnostics)
        {
            context.CancellationToken.ThrowIfCancellationRequested();
            context.ReportDiagnostic(
                diagnostic.Arguments.Length <= 1
                    ? Diagnostic.Create(
                        GetDescriptor(diagnostic.DescriptorId),
                        diagnostic.Location ?? Location.None,
                        diagnostic.Argument1
                    )
                    : Diagnostic.Create(
                        GetDescriptor(diagnostic.DescriptorId),
                        diagnostic.Location ?? Location.None,
                        diagnostic.Arguments.ToArray()
                    )
            );
        }

        if (result.HintName is not null && result.Source is not null)
        {
            context.AddSource(result.HintName, SourceText.From(result.Source, Encoding.UTF8));
        }

        // Model-facing surface and implementation files share one result so
        // per-model incremental isolation covers both with stable hint names.
        // A default (not merely empty) additional-sources array must not be
        // enumerated: ImmutableArray iteration over default throws.
        if (!result.AdditionalSources.IsDefaultOrEmpty)
        {
            foreach (var additional in result.AdditionalSources)
            {
                context.CancellationToken.ThrowIfCancellationRequested();
                context.AddSource(
                    additional.HintName,
                    SourceText.From(additional.Source, Encoding.UTF8)
                );
            }
        }
    }

    private static SparseGenerationResult Render(
        SparseGenerationAnalysis analysis,
        bool bclHashSetImplementsReadOnlySet,
        bool bclHashSetSupportsCapacity,
        CancellationToken cancellationToken
    )
    {
        cancellationToken.ThrowIfCancellationRequested();
        if (!analysis.Model.HasValue)
        {
            return new SparseGenerationResult(null, null, analysis.Diagnostics);
        }

        var model = analysis.Model.Value;
        // Union of both relocations: the surface plus the reloc-2 split
        // implementation file share one result, and the reloc-1 UI/session
        // family joins AdditionalSources under distinct hints so per-model
        // incremental isolation covers all of them.
        var (surface, implementation) = SparsePerModelEmitter.BuildSplitSurface(
            model,
            analysis.Members,
            analysis.PocoCloneModels,
            analysis.ReadOnlyViewModels,
            analysis.StructuralModels,
            bclHashSetImplementsReadOnlySet,
            bclHashSetSupportsCapacity,
            cancellationToken,
            Configuration,
            (code, generatedModel, members) =>
                SparseModelExtensionsEmitter.Append(code, generatedModel, members, Configuration)
        );
        var additional = SparsePerModelEmitter.BuildImplementationSources(
            model,
            analysis.Members,
            analysis.ReadOnlyViewModels,
            cancellationToken,
            Configuration
        );
        if (implementation.HasValue)
            additional = additional.Add(implementation.Value);
        return new SparseGenerationResult(
            model.HintName,
            surface,
            analysis.Diagnostics,
            additional
        );
    }

