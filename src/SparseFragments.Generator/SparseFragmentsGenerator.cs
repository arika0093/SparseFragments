    private static SparseGenerationResult RenderSinglePromoted(
        SparsePromotedModel promoted,
        bool bclHashSetImplementsReadOnlySet,
        bool bclHashSetSupportsCapacity,
        CancellationToken cancellationToken
    )
    {
        cancellationToken.ThrowIfCancellationRequested();
        // Promoted collisions stay render-time (the promoted path carries no
        // analysis diagnostics) but run on the shared collision primitive.
        var promotedCollision = SparseShapeValidation.FindFirstReservedNameCollision(
            promoted.Members,
            Configuration.EffectiveReservedGeneratedNames
        );
        if (promotedCollision is not null)
        {
            return new SparseGenerationResult(
                null,
                null,
                ImmutableArray.Create(
                    new SparseGeneratorDiagnostic(
                        Configuration.EffectiveDiagnosticIds.GeneratedNameCollision,
                        null,
                        promotedCollision
                    )
                )
            );
        }

        var hint = SparseFragmentEmitter.GetPromotedHintName(
            promoted.Model,
            Configuration.PromotedHintNameSuffix,
            cancellationToken
        );
        var (surface, implementation) = SparsePerModelEmitter.BuildPromotedSplitSurface(
            promoted,
            bclHashSetImplementsReadOnlySet,
            bclHashSetSupportsCapacity,
            cancellationToken,
            Configuration
        );
        var additional = SparsePerModelEmitter.BuildPromotedImplementationSources(
            promoted,
            cancellationToken,
            Configuration
        );
        if (implementation.HasValue)
            additional = additional.Add(implementation.Value);
        return new SparseGenerationResult(
            hint,
            surface,
            ImmutableArray<SparseGeneratorDiagnostic>.Empty,
            additional
        );
    }
