using System.Collections.Immutable;
using System.Text;
using System.Threading;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using SparseFragments.Generator.Shared;

namespace SparseFragments.Generator;

/// <summary>
/// Emits conventional EntityFrameworkCore mapping defaults for
/// <c>[SparseFragmentMapper]</c> types discovered by the ordinary generator.
/// </summary>
/// <remarks>
/// Product-specific surface, not Shared: Shared never hard-codes
/// SparseFragments runtime or mapper names. For each mapper implementing
/// <c>IEntityModelMapping&lt;TEntity, TDto&gt;</c> (the DTO may live in a
/// referenced Contracts assembly), the emitter writes an external companion
/// <c>{Mapper}_SparseEfDefaults</c> whose <c>RegisterDefaults</c> registers
/// source-level conventional registrations: same-name exact-type scalars via
/// <c>Member</c>, same-name nested models via recursive <c>Object</c>, and
/// same-name collections via <c>DeclareCollection</c> markers. Explicit
/// <c>Configure</c> entries replace each default exactly once at runtime.
/// Same-name members whose types differ produce SPF033 instead of a deferred
/// reflection failure. Members without a same-name entity counterpart stay
/// explicit-only and fail fast at mapper creation when unconfigured.
/// </remarks>
internal static class SparseEntityMapperEmitter
{
    internal const string MapperAttributeMetadataName =
        "SparseFragments.EntityFrameworkCore.SparseFragmentMapperAttribute";

    internal const string MappingInterfaceMetadataName =
        "SparseFragments.EntityFrameworkCore.IEntityModelMapping`2";

    internal const string MapBuilderMetadataName =
        "SparseFragments.EntityFrameworkCore.SparseEntityMapBuilder`2";

    private const int MaxDepth = 8;

    internal static SparseGenerationResult RenderMapper(
        INamedTypeSymbol mapper,
        CancellationToken cancellationToken
    )
    {
        cancellationToken.ThrowIfCancellationRequested();
        var location = mapper.Locations.FirstOrDefault();
        if (!TryResolveMappingPair(mapper, out var entityType, out var dtoType))
        {
            return new SparseGenerationResult(
                null,
                null,
                ImmutableArray.Create(
                    new SparseGeneratorDiagnostic(
                        SparseFragmentsDiagnosticIds.InvalidEntityMapperDeclaration,
                        location,
                        mapper.Name
                    )
                )
            );
        }

        var diagnostics = ImmutableArray.CreateBuilder<SparseGeneratorDiagnostic>();
        var code = new StringBuilder();
        code.AppendLine("// <auto-generated />");
        code.AppendLine("#nullable enable");
        var mapperNamespace = mapper.ContainingNamespace.IsGlobalNamespace
            ? null
            : mapper.ContainingNamespace.ToDisplayString();
        if (mapperNamespace is not null)
        {
            code.AppendLine($"namespace {mapperNamespace}");
            code.AppendLine("{");
        }

        // Nested mapper classes share their namespace: join enclosing type
        // names so two nested mappers with the same leaf name cannot collide.
        var nesting = new List<string>();
        for (
            var declaring = mapper.ContainingType;
            declaring is not null;
            declaring = declaring.ContainingType
        )
        {
            nesting.Add(declaring.Name);
        }

        nesting.Reverse();
        nesting.Add(mapper.Name);
        var companionName = string.Join("_", nesting) + "_SparseEfDefaults";
        // Supported-declarative Configure analysis: explicit Member/Ignore (and
        // scoped Object/Collection/Element) registrations suppress SPF033 for
        // the members they cover. A Configure body outside the analyzable
        // subset (helpers, control flow, dynamic calls) suppresses nothing
        // provable: diagnostics stay silent there and runtime plan validation
        // remains the backstop.
        var covered = SparseEntityMapperConfigureAnalysis.TryCollectCoveredMembers(mapper);
        var indent = mapperNamespace is null ? 0 : 1;
        AppendIndent(code, indent).Append("internal static class ").AppendLine(companionName);
        AppendIndent(code, indent).AppendLine("{");
        AppendIndent(code, indent + 1)
            .Append(
                "public static void RegisterDefaults(global::SparseFragments.EntityFrameworkCore.SparseEntityMapBuilder<"
            )
            .Append(entityType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat))
            .Append(", ")
            .Append(dtoType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat))
            .AppendLine("> builder)");
        AppendIndent(code, indent + 1).AppendLine("{");
        var visited = new HashSet<string>(StringComparer.Ordinal);
        EmitDefaults(
            code,
            indent + 2,
            entityType,
            dtoType,
            "builder",
            "dto",
            "entity",
            "child",
            0,
            string.Empty,
            false,
            covered,
            visited,
            diagnostics,
            location,
            mapper
        );
        AppendIndent(code, indent + 1).AppendLine("}");
        AppendIndent(code, indent + 1)
            .AppendLine("[global::System.Runtime.CompilerServices.ModuleInitializer]");
        AppendIndent(code, indent + 1).AppendLine("internal static void RegisterWithRuntime()");
        AppendIndent(code, indent + 1).AppendLine("{");
        AppendIndent(code, indent + 2)
            .Append(
                "global::SparseFragments.EntityFrameworkCore.Mapping.GeneratedDefaultsRegistry.Register<"
            )
            .Append(entityType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat))
            .Append(", ")
            .Append(dtoType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat))
            .Append(">(typeof(")
            .Append(mapper.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat))
            .AppendLine("), RegisterDefaults);");
        AppendIndent(code, indent + 1).AppendLine("}");
        AppendIndent(code, indent).AppendLine("}");
        if (mapperNamespace is not null)
        {
            code.AppendLine("}");
        }

        var hintName =
            (mapperNamespace is null ? string.Empty : mapperNamespace + ".")
            + companionName
            + ".SparseEfDefaults.g.cs";
        return new SparseGenerationResult(hintName, code.ToString(), diagnostics.ToImmutable());
    }

    private static bool TryResolveMappingPair(
        INamedTypeSymbol mapper,
        out INamedTypeSymbol entityType,
        out INamedTypeSymbol dtoType
    )
    {
        entityType = null!;
        dtoType = null!;
        foreach (var candidate in mapper.AllInterfaces)
        {
            if (
                candidate.OriginalDefinition.MetadataName != "IEntityModelMapping`2"
                || candidate.OriginalDefinition.ContainingNamespace.ToDisplayString()
                    != "SparseFragments.EntityFrameworkCore"
            )
            {
                continue;
            }

            if (
                candidate.TypeArguments.Length == 2
                && candidate.TypeArguments[0] is INamedTypeSymbol entity
                && candidate.TypeArguments[1] is INamedTypeSymbol dto
            )
            {
                entityType = entity;
                dtoType = dto;
                return true;
            }

            return false;
        }

        return false;
    }

    private static void EmitDefaults(
        StringBuilder code,
        int indent,
        INamedTypeSymbol entityType,
        INamedTypeSymbol dtoType,
        string builder,
        string dtoParameter,
        string entityParameter,
        string childParameter,
        int depth,
        string scope,
        bool collectionElement,
        HashSet<(string Scope, string Member)>? covered,
        HashSet<string> visited,
        ImmutableArray<SparseGeneratorDiagnostic>.Builder diagnostics,
        Location? location,
        INamedTypeSymbol mapper
    )
    {
        if (depth > MaxDepth)
        {
            return;
        }

        HashSet<string>? keyMembers = null;
        if (
            collectionElement
            && TryGetKeyDeclaration(
                dtoType,
                mapper,
                out _,
                out _,
                out _,
                out var keyComponentNames,
                out _
            )
        )
        {
            keyMembers = keyComponentNames.ToHashSet(StringComparer.Ordinal);
        }

        foreach (var dtoProperty in ListSettableProperties(dtoType, mapper))
        {
            var name = dtoProperty.Name;
            var entityMember = SparseEntityMapperSymbolHelpers.FindAccessibleEntityMember(
                entityType,
                name,
                mapper
            );
            var isKey = HasAttribute(dtoProperty, "SparseKeyAttribute");
            var isTemporaryKey = HasAttribute(dtoProperty, "SparseTemporaryKeyAttribute");
            var sameNameEntityType = entityMember is null
                ? null
                : SparseEntityMapperSymbolHelpers.GetMemberType(entityMember);
            var sameNameScalar =
                sameNameEntityType is not null
                && SparseEntityMapperSymbolHelpers.IsScalarType(dtoProperty.Type)
                && SparseEntityMapperSymbolHelpers.IsScalarType(sameNameEntityType)
                && SparseEntityMapperSymbolHelpers.SameType(dtoProperty.Type, sameNameEntityType);
            if (isTemporaryKey || (isKey && (!collectionElement || !sameNameScalar)))
            {
                AppendIndent(code, indent)
                    .Append(builder)
                    .Append(".Ignore(static ")
                    .Append(dtoParameter)
                    .Append(" => ")
                    .Append(dtoParameter)
                    .Append('.')
                    .Append(EscapeIdentifier(name))
                    .AppendLine(");");
                continue;
            }

            if (
                collectionElement
                && keyMembers?.Contains(name) == true
                && sameNameEntityType is not null
                && SparseEntityMapperSymbolHelpers.IsScalarType(dtoProperty.Type)
                && SparseEntityMapperSymbolHelpers.IsScalarType(sameNameEntityType)
                && !SparseEntityMapperSymbolHelpers.SameType(dtoProperty.Type, sameNameEntityType)
            )
            {
                AppendIndent(code, indent)
                    .Append(builder)
                    .Append(".Ignore(static ")
                    .Append(dtoParameter)
                    .Append(" => ")
                    .Append(dtoParameter)
                    .Append('.')
                    .Append(EscapeIdentifier(name))
                    .AppendLine(");");
                continue;
            }

            if (entityMember is null)
            {
                // A same-name member that exists but is unreachable from the
                // companion would fail with a CS error if referenced, so report
                // it instead of emitting an invalid selector. A missing
                // counterpart stays explicit-only by design (runtime plan
                // validation fails fast when unconfigured), as does anything
                // already covered by (or hidden behind an unanalyzable)
                // Configure.
                if (
                    covered is not null
                    && !covered.Contains((scope, name))
                    && SparseEntityMapperSymbolHelpers.FindEntityMember(entityType, name)
                        is not null
                )
                {
                    diagnostics.Add(
                        new SparseGeneratorDiagnostic(
                            SparseFragmentsDiagnosticIds.UnsupportedEntityMemberShape,
                            location,
                            $"{dtoType.Name}.{name} has no entity member accessible from the generated companion; make the entity member publicly accessible or Ignore() the DTO member"
                        )
                    );
                }

                continue;
            }

            var dtoPropertyType = dtoProperty.Type;
            if (SparseEntityMapperSymbolHelpers.IsCollectionType(dtoPropertyType))
            {
                AppendIndent(code, indent)
                    .Append(builder)
                    .Append(".DeclareCollection(static ")
                    .Append(dtoParameter)
                    .Append(" => ")
                    .Append(dtoParameter)
                    .Append('.')
                    .Append(EscapeIdentifier(name))
                    .Append(", static ")
                    .Append(entityParameter)
                    .Append(" => ")
                    .Append(entityParameter)
                    .Append('.')
                    .Append(EscapeIdentifier(name))
                    .AppendLine(");");
                var dtoElement = SparseEntityMapperSymbolHelpers.CollectionElementType(
                    dtoPropertyType
                );
                var entityElement = entityMember is not null
                    ? SparseEntityMapperSymbolHelpers.CollectionElementType(
                        SparseEntityMapperSymbolHelpers.GetMemberType(entityMember)
                    )
                    : null;
                if (
                    dtoElement is INamedTypeSymbol dtoElementNamed
                    && dtoElementNamed.TypeKind == TypeKind.Class
                    && !SparseEntityMapperSymbolHelpers.IsScalarType(dtoElement)
                    && entityElement is INamedTypeSymbol entityElementNamed
                    && entityElementNamed.TypeKind == TypeKind.Class
                )
                {
                    var hasKey = TryGetKeyDeclaration(
                        dtoElementNamed,
                        mapper,
                        out var keyProperty,
                        out var temporaryProperty,
                        out var unassignedKeyExpression,
                        out var keyMemberNames,
                        out var invalidTemporaryReason
                    );
                    if (invalidTemporaryReason is not null)
                    {
                        diagnostics.Add(
                            new SparseGeneratorDiagnostic(
                                SparseFragmentsDiagnosticIds.UnsupportedEntityMemberShape,
                                location,
                                invalidTemporaryReason
                            )
                        );
                    }

                    if (!hasKey && DeclaresKeyAttributes(dtoElementNamed))
                    {
                        diagnostics.Add(
                            new SparseGeneratorDiagnostic(
                                SparseFragmentsDiagnosticIds.UnsupportedEntityMemberShape,
                                location,
                                $"{dtoElementNamed.Name} declares key metadata that generated defaults cannot use; declare a single publicly readable [SparseKey] property (with unassigned semantics when a [SparseTemporaryKey] is present) or configure the collection explicitly"
                            )
                        );
                    }
                    // Path-scoped conventional element defaults: the explicit
                    // Collection(..., lines => lines.Element(...)) composes
                    // these underneath its own overrides, which replace each
                    // default exactly once. Policies stay explicit.
                    AppendIndent(code, indent)
                        .Append(builder)
                        .Append(".DeclareCollectionElement<")
                        .Append(
                            dtoElement.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)
                        )
                        .Append(", ")
                        .Append(
                            entityElement.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)
                        );
                    if (hasKey)
                    {
                        code.Append(", ")
                            .Append(
                                keyProperty!.Type.ToDisplayString(
                                    SymbolDisplayFormat.FullyQualifiedFormat
                                )
                            );
                    }

                    code.Append(">(static ")
                        .Append(dtoParameter)
                        .Append(" => ")
                        .Append(dtoParameter)
                        .Append('.')
                        .Append(EscapeIdentifier(name))
                        .Append(", ");
                    if (hasKey)
                    {
                        code.Append("static __key => __key.")
                            .Append(EscapeIdentifier(keyProperty!.Name))
                            .Append(", ")
                            .Append(unassignedKeyExpression ?? "default!")
                            .Append(", ")
                            .Append(unassignedKeyExpression is null ? "false" : "true")
                            .Append(", ");
                        if (temporaryProperty is null)
                        {
                            code.Append("null");
                        }
                        else
                        {
                            code.Append("static __key => __key.")
                                .Append(EscapeIdentifier(temporaryProperty.Name));
                        }

                        code.Append(", ");
                        if (
                            !SparseEntityMapperSymbolHelpers.IsTemporarySetterUsable(
                                temporaryProperty,
                                mapper
                            )
                        )
                        {
                            // An init-only (or otherwise non-assignable)
                            // temporary key cannot be written by a runtime
                            // delegate outside construction: pass null so the
                            // companion still compiles, and diagnose instead of
                            // emitting an invalid assignment. The runtime
                            // reports a clear MetadataMismatch if it ever needs
                            // to assign one.
                            if (temporaryProperty is not null)
                            {
                                diagnostics.Add(
                                    new SparseGeneratorDiagnostic(
                                        SparseFragmentsDiagnosticIds.UnsupportedEntityMemberShape,
                                        location,
                                        $"{dtoElementNamed.Name}.{temporaryProperty.Name} must be a publicly settable (non-init) property for generated defaults to assign temporary identities; use '{temporaryProperty.Name} {{ get; set; }}' or configure the collection explicitly"
                                    )
                                );
                            }

                            code.Append("null");
                        }
                        else
                        {
                            code.Append("static (__dto, __value) => __dto.")
                                .Append(EscapeIdentifier(temporaryProperty!.Name))
                                .Append(" = __value");
                        }

                        code.Append(", new string[] { ");
                        for (var keyIndex = 0; keyIndex < keyMemberNames.Length; keyIndex++)
                        {
                            if (keyIndex > 0)
                            {
                                code.Append(", ");
                            }

                            code.Append(
                                SymbolDisplay.FormatLiteral(keyMemberNames[keyIndex], true)
                            );
                        }

                        code.Append(" }, ");
                    }

                    code.Append("static ").Append(childParameter).AppendLine(" =>");
                    AppendIndent(code, indent).AppendLine("{");
                    EmitDefaults(
                        code,
                        indent + 1,
                        entityElementNamed,
                        dtoElementNamed,
                        childParameter,
                        dtoParameter,
                        entityParameter,
                        childParameter,
                        depth + 1,
                        scope.Length == 0 ? name : scope + "." + name,
                        true,
                        covered,
                        visited,
                        diagnostics,
                        location,
                        mapper
                    );
                    AppendIndent(code, indent).AppendLine("});");
                }

                continue;
            }

            var entityMemberType = SparseEntityMapperSymbolHelpers.GetMemberType(entityMember);
            if (entityMemberType is null)
            {
                continue;
            }

            if (
                SparseEntityMapperSymbolHelpers.IsScalarType(dtoPropertyType)
                && SparseEntityMapperSymbolHelpers.IsScalarType(entityMemberType)
            )
            {
                if (!SparseEntityMapperSymbolHelpers.SameType(dtoPropertyType, entityMemberType))
                {
                    // Explicit Configure owns this path: no default to emit and
                    // no diagnostic when the member is provably covered there.
                    // An unanalyzable Configure proves nothing either way, so
                    // diagnostics stay silent there with runtime plan validation
                    // as the backstop.
                    if (covered is null || covered.Contains((scope, name)))
                    {
                        continue;
                    }

                    diagnostics.Add(
                        new SparseGeneratorDiagnostic(
                            SparseFragmentsDiagnosticIds.IncompatibleEntityDefaultMapping,
                            location,
                            $"{dtoType.Name}.{name} ({dtoPropertyType.ToDisplayString()}) does not match {entityType.Name}.{name} ({entityMemberType.ToDisplayString()}); declare Member() with a convert callback or Ignore() the member"
                        )
                    );
                    continue;
                }

                AppendIndent(code, indent)
                    .Append(builder)
                    .Append(".Member(static ")
                    .Append(dtoParameter)
                    .Append(" => ")
                    .Append(dtoParameter)
                    .Append('.')
                    .Append(EscapeIdentifier(name))
                    .Append(", static ")
                    .Append(entityParameter)
                    .Append(" => ")
                    .Append(entityParameter)
                    .Append('.')
                    .Append(EscapeIdentifier(name))
                    .AppendLine(");");
                continue;
            }

            // Value types outside the scalar set (custom structs) cannot take
            // Object mappings, whose builder contracts require reference
            // types: report a clear diagnostic instead of emitting code that
            // violates the generic constraint.
            if (
                !SparseEntityMapperSymbolHelpers.IsScalarType(dtoPropertyType)
                && !SparseEntityMapperSymbolHelpers.IsScalarType(entityMemberType)
                && (dtoPropertyType.IsValueType || entityMemberType.IsValueType)
            )
            {
                diagnostics.Add(
                    new SparseGeneratorDiagnostic(
                        SparseFragmentsDiagnosticIds.UnsupportedEntityMemberShape,
                        location,
                        $"{dtoType.Name}.{name} ({dtoPropertyType.ToDisplayString()}) does not match {entityType.Name}.{name} ({entityMemberType.ToDisplayString()}); value-type members outside the scalar set need an explicit Member() conversion or Ignore()"
                    )
                );
                continue;
            }

            if (
                !SparseEntityMapperSymbolHelpers.IsScalarType(dtoPropertyType)
                && !SparseEntityMapperSymbolHelpers.IsScalarType(entityMemberType)
                && dtoPropertyType is INamedTypeSymbol dtoNested
                && entityMemberType is INamedTypeSymbol entityNested
                && entityMember is IPropertySymbol
            )
            {
                var visitKey = dtoNested.ToDisplayString() + "|" + entityNested.ToDisplayString();
                if (!visited.Add(visitKey))
                {
                    continue;
                }

                AppendIndent(code, indent)
                    .Append(builder)
                    .Append(".Object(static ")
                    .Append(dtoParameter)
                    .Append(" => ")
                    .Append(dtoParameter)
                    .Append('.')
                    .Append(EscapeIdentifier(name))
                    .Append(", static ")
                    .Append(entityParameter)
                    .Append(" => ")
                    .Append(entityParameter)
                    .Append('.')
                    .Append(EscapeIdentifier(name))
                    .Append(", static ")
                    .Append(childParameter)
                    .AppendLine(" =>");
                AppendIndent(code, indent).AppendLine("{");
                EmitDefaults(
                    code,
                    indent + 1,
                    entityNested,
                    dtoNested,
                    childParameter,
                    dtoParameter,
                    entityParameter,
                    childParameter,
                    depth + 1,
                    scope.Length == 0 ? name : scope + "." + name,
                    false,
                    covered,
                    visited,
                    diagnostics,
                    location,
                    mapper
                );
                AppendIndent(code, indent).AppendLine("});");
                visited.Remove(visitKey);
            }
        }
    }

    // Declarative Configure coverage analysis lives in
    // SparseEntityMapperConfigureAnalysis.
    private static List<IPropertySymbol> ListSettableProperties(
        INamedTypeSymbol type,
        INamedTypeSymbol mapper
    )
    {
        // Walk the base chain explicitly: inherited writable properties take
        // conventional defaults too, with the nearest declaration winning.
        // Only members (and member types) reachable from the emitted companion
        // qualify: private/protected or cross-assembly internal members would
        // fail with CS errors when named from the unrelated companion type.
        // Init-only setters stay eligible here because conventional
        // Member/Object/Collection selectors only read; the temporary-key
        // assignment delegate guards IsInitOnly separately.
        var properties = new List<IPropertySymbol>();
        var seen = new HashSet<string>(StringComparer.Ordinal);
        for (
            var current = type;
            current is not null && current.SpecialType != SpecialType.System_Object;
            current = current.BaseType
        )
        {
            foreach (var member in current.GetMembers().OfType<IPropertySymbol>())
            {
                if (
                    member.IsStatic
                    || member.IsIndexer
                    || member.GetMethod is null
                    || member.SetMethod is null
                    || !seen.Add(member.Name)
                )
                {
                    continue;
                }

                if (
                    !SparseEntityMapperSymbolHelpers.IsAccessibleFromCompanion(member, mapper)
                    || !SparseEntityMapperSymbolHelpers.IsAccessibleFromCompanion(
                        member.GetMethod,
                        mapper
                    )
                    || !SparseEntityMapperSymbolHelpers.IsAccessibleFromCompanion(
                        member.SetMethod,
                        mapper
                    )
                    || !SparseEntityMapperSymbolHelpers.IsTypeAccessibleFromCompanion(
                        member.Type,
                        mapper
                    )
                )
                {
                    continue;
                }

                properties.Add(member);
            }
        }

        return properties;
    }

    private static bool DeclaresKeyAttributes(INamedTypeSymbol elementType) =>
        ListInstanceProperties(elementType)
            .Any(property =>
                HasAttribute(property, "SparseKeyAttribute")
                || HasAttribute(property, "SparseTemporaryKeyAttribute")
            );

    private static bool HasAttribute(ISymbol symbol, string metadataName) =>
        symbol
            .GetAttributes()
            .Any(attribute =>
                attribute.AttributeClass?.ToDisplayString() == "SparseFragments." + metadataName
            );

    private static bool TryGetKeyDeclaration(
        INamedTypeSymbol elementType,
        INamedTypeSymbol mapper,
        out IPropertySymbol? keyProperty,
        out IPropertySymbol? temporaryProperty,
        out string? unassignedKeyExpression,
        out string[] keyMemberNames,
        out string? invalidTemporaryReason
    )
    {
        var properties = ListInstanceProperties(elementType);
        var keys = properties
            .Where(static property => HasAttribute(property, "SparseKeyAttribute"))
            .ToArray();
        var temporaries = properties
            .Where(static property => HasAttribute(property, "SparseTemporaryKeyAttribute"))
            .ToArray();
        keyProperty = null;
        temporaryProperty = null;
        unassignedKeyExpression = null;
        keyMemberNames = [];
        invalidTemporaryReason = null;
        var keyGetMethod = keys.Length == 1 ? keys[0].GetMethod : null;
        if (
            keys.Length != 1
            || keyGetMethod is null
            || keys[0].DeclaredAccessibility != Accessibility.Public
            || !SparseEntityMapperSymbolHelpers.IsAccessibleFromCompanion(keys[0], mapper)
            || !SparseEntityMapperSymbolHelpers.IsAccessibleFromCompanion(keyGetMethod, mapper)
            || !SparseEntityMapperSymbolHelpers.IsTypeAccessibleFromCompanion(keys[0].Type, mapper)
            || temporaries.Length > 1
        )
        {
            return false;
        }

        keyProperty = keys[0];
        // A usable temporary identity mirrors the Shared analyzer's declaration
        // rules (single, readable, Guid?, not combined with [SparseKey]) plus
        // companion reachability. Init-only setters stay eligible here because
        // correlation only reads; assignability is guarded separately when the
        // setter delegate is emitted.
        if (temporaries.Length == 1)
        {
            var candidate = temporaries[0];
            if (
                candidate.IsStatic
                || candidate.IsIndexer
                || candidate.GetMethod is null
                || candidate.DeclaredAccessibility != Accessibility.Public
                || candidate.GetMethod.DeclaredAccessibility != Accessibility.Public
                || !SparseEntityMapperSymbolHelpers.IsAccessibleFromCompanion(candidate, mapper)
                || HasAttribute(candidate, "SparseKeyAttribute")
                || candidate.Type
                    is not INamedTypeSymbol
                    {
                        OriginalDefinition.SpecialType: SpecialType.System_Nullable_T,
                        TypeArguments.Length: 1,
                    } temporaryType
                || temporaryType.TypeArguments[0].ToDisplayString() != "System.Guid"
            )
            {
                invalidTemporaryReason =
                    $"{elementType.Name}.{candidate.Name} is not a usable temporary identity; mark a single publicly readable Guid? property (without [SparseKey]) that is accessible from the generated companion";
            }
            else
            {
                temporaryProperty = candidate;
            }
        }
        var keyAttribute = keyProperty
            .GetAttributes()
            .First(static attribute =>
                attribute.AttributeClass?.ToDisplayString() == "SparseFragments.SparseKeyAttribute"
            );
        foreach (var argument in keyAttribute.NamedArguments)
        {
            if (argument.Key == "Unassigned")
            {
                unassignedKeyExpression = ConstantExpression(argument.Value);
                break;
            }
        }

        var writableNames = ListSettableProperties(elementType, mapper)
            .Select(static property => property.Name)
            .ToHashSet(StringComparer.Ordinal);
        var members = new HashSet<string>(StringComparer.Ordinal) { keyProperty.Name };
        foreach (var reference in keyProperty.DeclaringSyntaxReferences)
        {
            if (reference.GetSyntax() is not PropertyDeclarationSyntax declaration)
            {
                continue;
            }

            var syntax = declaration.ExpressionBody?.Expression;
            if (syntax is null)
            {
                var getter = declaration.AccessorList?.Accessors.FirstOrDefault(static accessor =>
                    accessor.Keyword.ValueText == "get"
                );
                syntax = getter?.ExpressionBody?.Expression;
                if (syntax is null && getter?.Body is not null)
                {
                    foreach (
                        var identifier in getter
                            .Body.DescendantNodesAndSelf()
                            .OfType<IdentifierNameSyntax>()
                            .Where(identifier =>
                                writableNames.Contains(identifier.Identifier.ValueText)
                            )
                    )
                    {
                        members.Add(identifier.Identifier.ValueText);
                    }
                }
            }

            if (syntax is not null)
            {
                foreach (
                    var identifier in syntax
                        .DescendantNodesAndSelf()
                        .OfType<IdentifierNameSyntax>()
                        .Where(identifier =>
                            writableNames.Contains(identifier.Identifier.ValueText)
                        )
                )
                {
                    members.Add(identifier.Identifier.ValueText);
                }
            }
        }

        keyMemberNames = members.ToArray();
        return true;
    }

    private static List<IPropertySymbol> ListInstanceProperties(INamedTypeSymbol type)
    {
        var properties = new List<IPropertySymbol>();
        var seen = new HashSet<string>(StringComparer.Ordinal);
        for (
            var current = type;
            current is not null && current.SpecialType != SpecialType.System_Object;
            current = current.BaseType
        )
        {
            foreach (var property in current.GetMembers().OfType<IPropertySymbol>())
            {
                if (
                    !property.IsStatic
                    && !property.IsIndexer
                    && property.GetMethod is not null
                    && seen.Add(property.Name)
                )
                {
                    properties.Add(property);
                }
            }
        }

        return properties;
    }

    private static string? ConstantExpression(TypedConstant constant)
    {
        if (constant.IsNull || constant.Type is null || constant.Value is null)
        {
            return null;
        }

        var value = constant.Value;
        if (constant.Type.TypeKind == TypeKind.Enum)
        {
            return "("
                + constant.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)
                + ")"
                + Convert.ToString(value, System.Globalization.CultureInfo.InvariantCulture);
        }

        return constant.Type.SpecialType switch
        {
            SpecialType.System_String => SymbolDisplay.FormatLiteral((string)value, true),
            SpecialType.System_Char => SymbolDisplay.FormatLiteral((char)value, true),
            SpecialType.System_Boolean => (bool)value ? "true" : "false",
            SpecialType.System_Byte => "(byte)"
                + Convert.ToString(value, System.Globalization.CultureInfo.InvariantCulture),
            SpecialType.System_SByte => "(sbyte)"
                + Convert.ToString(value, System.Globalization.CultureInfo.InvariantCulture),
            SpecialType.System_Int16 => "(short)"
                + Convert.ToString(value, System.Globalization.CultureInfo.InvariantCulture),
            SpecialType.System_UInt16 => "(ushort)"
                + Convert.ToString(value, System.Globalization.CultureInfo.InvariantCulture),
            SpecialType.System_Int32 => Convert.ToString(
                value,
                System.Globalization.CultureInfo.InvariantCulture
            ),
            SpecialType.System_UInt32 => Convert.ToString(
                value,
                System.Globalization.CultureInfo.InvariantCulture
            ) + "U",
            SpecialType.System_Int64 => Convert.ToString(
                value,
                System.Globalization.CultureInfo.InvariantCulture
            ) + "L",
            SpecialType.System_UInt64 => Convert.ToString(
                value,
                System.Globalization.CultureInfo.InvariantCulture
            ) + "UL",
            SpecialType.System_Single => Convert.ToString(
                value,
                System.Globalization.CultureInfo.InvariantCulture
            ) + "F",
            SpecialType.System_Double => Convert.ToString(
                value,
                System.Globalization.CultureInfo.InvariantCulture
            ) + "D",
            SpecialType.System_Decimal => Convert.ToString(
                value,
                System.Globalization.CultureInfo.InvariantCulture
            ) + "M",
            _ => null,
        };
    }

    private static StringBuilder AppendIndent(StringBuilder code, int indent)
    {
        for (var index = 0; index < indent; index++)
        {
            code.Append("    ");
        }

        return code;
    }

    // A valid model property may spell a reserved or contextual keyword
    // (@event): the symbol name needs an escape for member access emission.
    internal static string EscapeIdentifier(string name) =>
        SyntaxFacts.GetKeywordKind(name) != SyntaxKind.None
        || SyntaxFacts.GetContextualKeywordKind(name) != SyntaxKind.None
            ? "@" + name
            : name;
}
