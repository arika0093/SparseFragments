using System.Collections.Immutable;
using System.Text;
using System.Threading;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using SparseFragments.Generator.Shared;

namespace SparseFragments.Generator;

/// <summary>
/// Emits conventional EntityFrameworkCore mapping defaults for
/// <c>[SparseFragmentMapper]</c> types discovered by the ordinary generator.
/// </summary>
/// <remarks>
/// Product-specific surface, not Shared: Shared never hard-codes
/// SparseFragments runtime or mapper names. For each mapper implementing
/// <c>IEntityModelMapping&lt;TEntity, TDto&gt;</c> (the DTO may live in a
/// referenced Contracts assembly), the emitter writes an external companion
/// <c>{Mapper}_SparseEfDefaults</c> whose <c>RegisterDefaults</c> registers
/// source-level conventional registrations: same-name exact-type scalars via
/// <c>Member</c>, same-name nested models via recursive <c>Object</c>, and
/// same-name collections via <c>DeclareCollection</c> markers. Explicit
/// <c>Configure</c> entries replace each default exactly once at runtime.
/// Same-name members whose types differ produce SPF033 instead of a deferred
/// reflection failure. Members without a same-name entity counterpart stay
/// explicit-only and fail fast at mapper creation when unconfigured.
/// </remarks>
internal static class SparseEntityMapperEmitter
{
    internal const string MapperAttributeMetadataName =
        "SparseFragments.EntityFrameworkCore.SparseFragmentMapperAttribute";

    internal const string MappingInterfaceMetadataName =
        "SparseFragments.EntityFrameworkCore.IEntityModelMapping`2";

    internal const string MapBuilderMetadataName =
        "SparseFragments.EntityFrameworkCore.SparseEntityMapBuilder`2";

    private const int MaxDepth = 8;

    internal static SparseGenerationResult RenderMapper(
        INamedTypeSymbol mapper,
        CancellationToken cancellationToken
    )
    {
        cancellationToken.ThrowIfCancellationRequested();
        var location = mapper.Locations.FirstOrDefault();
        if (!TryResolveMappingPair(mapper, out var entityType, out var dtoType))
        {
            return new SparseGenerationResult(
                null,
                null,
                ImmutableArray.Create(
                    new SparseGeneratorDiagnostic(
                        SparseFragmentsDiagnosticIds.InvalidEntityMapperDeclaration,
                        location,
                        mapper.Name
                    )
                )
            );
        }

        var diagnostics = ImmutableArray.CreateBuilder<SparseGeneratorDiagnostic>();
        var code = new StringBuilder();
        code.AppendLine("// <auto-generated />");
        code.AppendLine("#nullable enable");
        var mapperNamespace = mapper.ContainingNamespace.IsGlobalNamespace
            ? null
            : mapper.ContainingNamespace.ToDisplayString();
        if (mapperNamespace is not null)
        {
            code.AppendLine($"namespace {mapperNamespace}");
            code.AppendLine("{");
        }

        // Nested mapper classes share their namespace: join enclosing type
        // names so two nested mappers with the same leaf name cannot collide.
        // GeneratedDefaults.TryApply replicates this rule for lookup.
        var nesting = new List<string>();
        for (
            var declaring = mapper.ContainingType;
            declaring is not null;
            declaring = declaring.ContainingType
        )
        {
            nesting.Add(declaring.Name);
        }

        nesting.Reverse();
        nesting.Add(mapper.Name);
        var companionName = string.Join("_", nesting) + "_SparseEfDefaults";
        // Supported-declarative Configure analysis: explicit Member/Ignore (and
        // scoped Object/Collection/Element) registrations suppress SPF033 for
        // the members they cover. A Configure body outside the analyzable
        // subset (helpers, control flow, dynamic calls) suppresses nothing
        // provable: diagnostics stay silent there and runtime plan validation
        // remains the backstop.
        var covered = TryCollectCoveredMembers(mapper);
        var indent = mapperNamespace is null ? 0 : 1;
        AppendIndent(code, indent).Append("internal static class ").AppendLine(companionName);
        AppendIndent(code, indent).AppendLine("{");
        AppendIndent(code, indent + 1)
            .Append(
                "public static void RegisterDefaults(global::SparseFragments.EntityFrameworkCore.SparseEntityMapBuilder<"
            )
            .Append(entityType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat))
            .Append(", ")
            .Append(dtoType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat))
            .AppendLine("> builder)");
        AppendIndent(code, indent + 1).AppendLine("{");
        var visited = new HashSet<string>(StringComparer.Ordinal);
        EmitDefaults(
            code,
            indent + 2,
            entityType,
            dtoType,
            "builder",
            "dto",
            "entity",
            "child",
            0,
            string.Empty,
            covered,
            visited,
            diagnostics,
            location
        );
        AppendIndent(code, indent + 1).AppendLine("}");
        AppendIndent(code, indent).AppendLine("}");
        if (mapperNamespace is not null)
        {
            code.AppendLine("}");
        }

        var hintName =
            (mapperNamespace is null ? string.Empty : mapperNamespace + ".")
            + companionName
            + ".SparseEfDefaults.g.cs";
        return new SparseGenerationResult(hintName, code.ToString(), diagnostics.ToImmutable());
    }

    private static bool TryResolveMappingPair(
        INamedTypeSymbol mapper,
        out INamedTypeSymbol entityType,
        out INamedTypeSymbol dtoType
    )
    {
        entityType = null!;
        dtoType = null!;
        foreach (var candidate in mapper.AllInterfaces)
        {
            if (
                candidate.OriginalDefinition.MetadataName != "IEntityModelMapping`2"
                || candidate.OriginalDefinition.ContainingNamespace.ToDisplayString()
                    != "SparseFragments.EntityFrameworkCore"
            )
            {
                continue;
            }

            if (
                candidate.TypeArguments.Length == 2
                && candidate.TypeArguments[0] is INamedTypeSymbol entity
                && candidate.TypeArguments[1] is INamedTypeSymbol dto
            )
            {
                entityType = entity;
                dtoType = dto;
                return true;
            }

            return false;
        }

        return false;
    }

    private static void EmitDefaults(
        StringBuilder code,
        int indent,
        INamedTypeSymbol entityType,
        INamedTypeSymbol dtoType,
        string builder,
        string dtoParameter,
        string entityParameter,
        string childParameter,
        int depth,
        string scope,
        HashSet<(string Scope, string Member)>? covered,
        HashSet<string> visited,
        ImmutableArray<SparseGeneratorDiagnostic>.Builder diagnostics,
        Location? location
    )
    {
        if (depth > MaxDepth)
        {
            return;
        }

        foreach (var dtoProperty in ListSettableProperties(dtoType))
        {
            var name = dtoProperty.Name;
            var entityMember = FindEntityMember(entityType, name);
            if (entityMember is null)
            {
                continue;
            }

            var dtoPropertyType = dtoProperty.Type;
            if (IsCollectionType(dtoPropertyType))
            {
                AppendIndent(code, indent)
                    .Append(builder)
                    .Append(".DeclareCollection(static ")
                    .Append(dtoParameter)
                    .Append(" => ")
                    .Append(dtoParameter)
                    .Append('.')
                    .Append(EscapeIdentifier(name))
                    .Append(", static ")
                    .Append(entityParameter)
                    .Append(" => ")
                    .Append(entityParameter)
                    .Append('.')
                    .Append(EscapeIdentifier(name))
                    .AppendLine(");");
                var dtoElement = CollectionElementType(dtoPropertyType);
                var entityElement = entityMember is not null
                    ? CollectionElementType(GetMemberType(entityMember))
                    : null;
                if (
                    dtoElement is INamedTypeSymbol dtoElementNamed
                    && dtoElementNamed.TypeKind == TypeKind.Class
                    && !IsScalarType(dtoElement)
                    && entityElement is INamedTypeSymbol entityElementNamed
                    && entityElementNamed.TypeKind == TypeKind.Class
                )
                {
                    // Path-scoped conventional element defaults: the explicit
                    // Collection(..., lines => lines.Element(...)) composes
                    // these underneath its own overrides, which replace each
                    // default exactly once. Policies stay explicit.
                    AppendIndent(code, indent)
                        .Append(builder)
                        .Append(".DeclareCollectionElement<")
                        .Append(
                            dtoElement.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)
                        )
                        .Append(", ")
                        .Append(
                            entityElement.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)
                        )
                        .Append(">(static ")
                        .Append(dtoParameter)
                        .Append(" => ")
                        .Append(dtoParameter)
                        .Append('.')
                        .Append(EscapeIdentifier(name))
                        .Append(", static ")
                        .Append(childParameter)
                        .AppendLine(" =>");
                    AppendIndent(code, indent).AppendLine("{");
                    EmitDefaults(
                        code,
                        indent + 1,
                        entityElementNamed,
                        dtoElementNamed,
                        childParameter,
                        dtoParameter,
                        entityParameter,
                        childParameter,
                        depth + 1,
                        scope.Length == 0 ? name : scope + "." + name,
                        covered,
                        visited,
                        diagnostics,
                        location
                    );
                    AppendIndent(code, indent).AppendLine("});");
                }

                continue;
            }

            var entityMemberType = GetMemberType(entityMember);
            if (entityMemberType is null)
            {
                continue;
            }

            if (IsScalarType(dtoPropertyType) && IsScalarType(entityMemberType))
            {
                if (!SameType(dtoPropertyType, entityMemberType))
                {
                    // Explicit Configure owns this path: no default to emit and
                    // no diagnostic when the member is provably covered there.
                    // An unanalyzable Configure proves nothing either way, so
                    // diagnostics stay silent there with runtime plan validation
                    // as the backstop.
                    if (covered is null || covered.Contains((scope, name)))
                    {
                        continue;
                    }

                    diagnostics.Add(
                        new SparseGeneratorDiagnostic(
                            SparseFragmentsDiagnosticIds.IncompatibleEntityDefaultMapping,
                            location,
                            $"{dtoType.Name}.{name} ({dtoPropertyType.ToDisplayString()}) does not match {entityType.Name}.{name} ({entityMemberType.ToDisplayString()}); declare Member() with a convert callback or Ignore() the member"
                        )
                    );
                    continue;
                }

                AppendIndent(code, indent)
                    .Append(builder)
                    .Append(".Member(static ")
                    .Append(dtoParameter)
                    .Append(" => ")
                    .Append(dtoParameter)
                    .Append('.')
                    .Append(EscapeIdentifier(name))
                    .Append(", static ")
                    .Append(entityParameter)
                    .Append(" => ")
                    .Append(entityParameter)
                    .Append('.')
                    .Append(EscapeIdentifier(name))
                    .AppendLine(");");
                continue;
            }

            // Value types outside the scalar set (custom structs) cannot take
            // Object mappings, whose builder contracts require reference
            // types: report a clear diagnostic instead of emitting code that
            // violates the generic constraint.
            if (
                !IsScalarType(dtoPropertyType)
                && !IsScalarType(entityMemberType)
                && (dtoPropertyType.IsValueType || entityMemberType.IsValueType)
            )
            {
                diagnostics.Add(
                    new SparseGeneratorDiagnostic(
                        SparseFragmentsDiagnosticIds.UnsupportedEntityMemberShape,
                        location,
                        $"{dtoType.Name}.{name} ({dtoPropertyType.ToDisplayString()}) does not match {entityType.Name}.{name} ({entityMemberType.ToDisplayString()}); value-type members outside the scalar set need an explicit Member() conversion or Ignore()"
                    )
                );
                continue;
            }

            if (
                !IsScalarType(dtoPropertyType)
                && !IsScalarType(entityMemberType)
                && dtoPropertyType is INamedTypeSymbol dtoNested
                && entityMemberType is INamedTypeSymbol entityNested
                && entityMember is IPropertySymbol
            )
            {
                var visitKey = dtoNested.ToDisplayString() + "|" + entityNested.ToDisplayString();
                if (!visited.Add(visitKey))
                {
                    continue;
                }

                AppendIndent(code, indent)
                    .Append(builder)
                    .Append(".Object(static ")
                    .Append(dtoParameter)
                    .Append(" => ")
                    .Append(dtoParameter)
                    .Append('.')
                    .Append(EscapeIdentifier(name))
                    .Append(", static ")
                    .Append(entityParameter)
                    .Append(" => ")
                    .Append(entityParameter)
                    .Append('.')
                    .Append(EscapeIdentifier(name))
                    .Append(", static ")
                    .Append(childParameter)
                    .AppendLine(" =>");
                AppendIndent(code, indent).AppendLine("{");
                EmitDefaults(
                    code,
                    indent + 1,
                    entityNested,
                    dtoNested,
                    childParameter,
                    dtoParameter,
                    entityParameter,
                    childParameter,
                    depth + 1,
                    scope.Length == 0 ? name : scope + "." + name,
                    covered,
                    visited,
                    diagnostics,
                    location
                );
                AppendIndent(code, indent).AppendLine("});");
                visited.Remove(visitKey);
            }
        }
    }

    // Supported declarative Configure subset for SPF033 suppression: direct
    // typed builder calls whose DTO selector is a single member access, with
    // Object/Collection/Element lambdas tracked for scope. Anything else
    // (helpers, control flow, dynamic calls) makes the whole Configure
    // unanalyzable, in which case nothing is provable and diagnostics stay
    // silent with runtime plan validation as the backstop.
    private static HashSet<(string Scope, string Member)>? TryCollectCoveredMembers(
        INamedTypeSymbol mapper
    )
    {
        var configure = mapper
            .GetMembers("Configure")
            .OfType<IMethodSymbol>()
            .FirstOrDefault(static method => method.Parameters.Length == 1);
        if (configure is null)
        {
            return null;
        }

        var declaration =
            configure.DeclaringSyntaxReferences.FirstOrDefault()?.GetSyntax()
            as MethodDeclarationSyntax;
        if (declaration?.Body is not { } body)
        {
            return null;
        }

        var covered = new HashSet<(string Scope, string Member)>();
        var vars = new Dictionary<string, string>(StringComparer.Ordinal)
        {
            [configure.Parameters[0].Name] = string.Empty,
        };
        return ProcessConfigureBlock(body, vars, covered) ? covered : null;
    }

    private static bool ProcessConfigureBlock(
        BlockSyntax block,
        Dictionary<string, string> vars,
        HashSet<(string Scope, string Member)> covered
    )
    {
        foreach (var statement in block.Statements)
        {
            if (
                statement
                    is not ExpressionStatementSyntax
                    {
                        Expression: InvocationExpressionSyntax invocation
                    }
                || !ProcessConfigureInvocation(invocation, vars, covered)
            )
            {
                return false;
            }
        }

        return true;
    }

    private static bool ProcessConfigureInvocation(
        InvocationExpressionSyntax invocation,
        Dictionary<string, string> vars,
        HashSet<(string Scope, string Member)> covered
    )
    {
        if (
            invocation.Expression
                is not MemberAccessExpressionSyntax
                {
                    Expression: IdentifierNameSyntax receiver,
                    Name: IdentifierNameSyntax method
                }
            || !vars.TryGetValue(receiver.Identifier.Text, out var scope)
        )
        {
            return false;
        }

        var arguments = invocation.ArgumentList.Arguments;
        switch (method.Identifier.Text)
        {
            case "Member":
                // Only a converter-bearing Member resolves a member: a
                // two-argument or policy-only Member cannot supply a conversion.
                if (
                    arguments.Count > 0
                    && HasConverterArgument(arguments)
                    && TrySingleMember(arguments[0].Expression, out var member)
                )
                {
                    covered.Add((scope, member));
                }

                return true;
            case "Write":
            case "Ignore":
                if (
                    arguments.Count > 0
                    && TrySingleMember(arguments[0].Expression, out var written)
                )
                {
                    covered.Add((scope, written));
                }

                return true;
            case "OnMissing":
            case "AllowWrite":
                // Policies alone resolve nothing; still supported syntax.
                return true;
            case "Object":
            case "Collection":
                if (
                    arguments.Count == 0
                    || !TrySingleMember(arguments[0].Expression, out var childMember)
                )
                {
                    return true;
                }

                covered.Add((scope, childMember));
                if (
                    arguments.Count < 3
                    || !TryLambdaStatements(
                        arguments[2].Expression,
                        out var parameter,
                        out var statements
                    )
                )
                {
                    return arguments.Count < 3;
                }

                var childScope = scope.Length == 0 ? childMember : scope + "." + childMember;
                var nested = new Dictionary<string, string>(vars, StringComparer.Ordinal)
                {
                    [parameter] = childScope,
                };
                return ProcessConfigureStatements(statements, nested, covered);
            case "Element":
                if (
                    arguments.Count == 0
                    || !TryLambdaStatements(
                        arguments[0].Expression,
                        out var elementParameter,
                        out var elementStatements
                    )
                )
                {
                    return false;
                }

                var scoped = new Dictionary<string, string>(vars, StringComparer.Ordinal)
                {
                    [elementParameter] = scope,
                };
                return ProcessConfigureStatements(elementStatements, scoped, covered);
            case "MissingDefault":
            case "DeclareCollection":
            case "DeclareCollectionElement":
            case "Key":
            case "Create":
            case "Remove":
            case "Delete":
            case "Detach":
            case "SoftDelete":
            case "Order":
            case "UnassignedKey":
                return true;
            default:
                return false;
        }
    }

    private static bool ProcessConfigureStatements(
        IReadOnlyList<StatementSyntax> statements,
        Dictionary<string, string> vars,
        HashSet<(string Scope, string Member)> covered
    )
    {
        foreach (var statement in statements)
        {
            if (
                statement
                    is not ExpressionStatementSyntax
                    {
                        Expression: InvocationExpressionSyntax invocation
                    }
                || !ProcessConfigureInvocation(invocation, vars, covered)
            )
            {
                return false;
            }
        }

        return true;
    }

    // A converter lives past the DTO/entity selector pair: the third or fourth
    // argument as a lambda (a policy enum member access is not one).
    private static bool HasConverterArgument(SeparatedSyntaxList<ArgumentSyntax> arguments)
    {
        for (var index = 2; index < arguments.Count; index++)
        {
            if (
                arguments[index].Expression
                is SimpleLambdaExpressionSyntax
                    or ParenthesizedLambdaExpressionSyntax
            )
            {
                return true;
            }
        }

        return false;
    }

    private static bool TrySingleMember(ExpressionSyntax expression, out string member)
    {
        member = string.Empty;
        if (
            expression
                is SimpleLambdaExpressionSyntax
                {
                    Parameter: var token,
                    Body: MemberAccessExpressionSyntax
                    {
                        Expression: IdentifierNameSyntax receiver,
                        Name: IdentifierNameSyntax name
                    }
                }
            && receiver.Identifier.Text == token.Identifier.Text
        )
        {
            member = name.Identifier.Text;
            return true;
        }

        if (
            expression
                is ParenthesizedLambdaExpressionSyntax
                {
                    ParameterList.Parameters.Count: 1
                } parenthesized
            && parenthesized.Body
                is MemberAccessExpressionSyntax
                {
                    Expression: IdentifierNameSyntax parenthesizedReceiver,
                    Name: IdentifierNameSyntax parenthesizedName
                }
            && parenthesizedReceiver.Identifier.Text
                == parenthesized.ParameterList.Parameters[0].Identifier.Text
        )
        {
            member = parenthesizedName.Identifier.Text;
            return true;
        }

        return false;
    }

    private static bool TryLambdaStatements(
        ExpressionSyntax expression,
        out string parameter,
        out IReadOnlyList<StatementSyntax> statements
    )
    {
        parameter = string.Empty;
        statements = [];
        if (expression is SimpleLambdaExpressionSyntax simple)
        {
            parameter = simple.Parameter.Identifier.Text;
            if (simple.Body is BlockSyntax block)
            {
                statements = block.Statements;
                return true;
            }

            if (simple.Body is ExpressionSyntax body)
            {
                statements = [SyntaxFactory.ExpressionStatement(body)];
                return true;
            }

            return false;
        }

        if (
            expression is ParenthesizedLambdaExpressionSyntax
            {
                ParameterList.Parameters.Count: 1
            } parenthesized
        )
        {
            parameter = parenthesized.ParameterList.Parameters[0].Identifier.Text;
            if (parenthesized.Body is BlockSyntax parenthesizedBlock)
            {
                statements = parenthesizedBlock.Statements;
                return true;
            }

            if (parenthesized.Body is ExpressionSyntax parenthesizedBody)
            {
                statements = [SyntaxFactory.ExpressionStatement(parenthesizedBody)];
                return true;
            }
        }

        return false;
    }

    private static List<IPropertySymbol> ListSettableProperties(INamedTypeSymbol type)
    {
        // Walk the base chain explicitly: inherited writable properties take
        // conventional defaults too, with the nearest declaration winning.
        var properties = new List<IPropertySymbol>();
        var seen = new HashSet<string>(StringComparer.Ordinal);
        for (
            var current = type;
            current is not null && current.SpecialType != SpecialType.System_Object;
            current = current.BaseType
        )
        {
            foreach (var member in current.GetMembers().OfType<IPropertySymbol>())
            {
                if (
                    member.IsStatic
                    || member.IsIndexer
                    || member.GetMethod is null
                    || member.SetMethod is null
                    || !seen.Add(member.Name)
                )
                {
                    continue;
                }

                properties.Add(member);
            }
        }

        return properties;
    }

    private static ISymbol? FindEntityMember(INamedTypeSymbol entityType, string name)
    {
        for (
            var current = entityType;
            current is not null && current.SpecialType != SpecialType.System_Object;
            current = current.BaseType
        )
        {
            foreach (var member in current.GetMembers(name))
            {
                if (member.IsStatic)
                {
                    continue;
                }

                if (member is IPropertySymbol property && property.GetMethod is not null)
                {
                    return property;
                }

                if (member is IFieldSymbol)
                {
                    return member;
                }
            }
        }

        return null;
    }

    private static ITypeSymbol? GetMemberType(ISymbol member) =>
        member switch
        {
            IPropertySymbol property => property.Type,
            IFieldSymbol field => field.Type,
            _ => null,
        };

    private static bool IsScalarType(ITypeSymbol type)
    {
        var underlying =
            type is INamedTypeSymbol named
            && named.OriginalDefinition.SpecialType == SpecialType.System_Nullable_T
            && named.TypeArguments.Length == 1
                ? named.TypeArguments[0]
                : type;
        switch (underlying.SpecialType)
        {
            case SpecialType.System_Boolean:
            case SpecialType.System_Char:
            case SpecialType.System_SByte:
            case SpecialType.System_Byte:
            case SpecialType.System_Int16:
            case SpecialType.System_UInt16:
            case SpecialType.System_Int32:
            case SpecialType.System_UInt32:
            case SpecialType.System_Int64:
            case SpecialType.System_UInt64:
            case SpecialType.System_Single:
            case SpecialType.System_Double:
            case SpecialType.System_Decimal:
            case SpecialType.System_String:
            case SpecialType.System_DateTime:
                return true;
            default:
                break;
        }

        if (underlying.TypeKind == TypeKind.Enum)
        {
            return true;
        }

        if (underlying is INamedTypeSymbol namedType)
        {
            var full = namedType.OriginalDefinition.ToDisplayString();
            if (
                full == "System.DateTimeOffset"
                || full == "System.DateOnly"
                || full == "System.TimeOnly"
                || full == "System.TimeSpan"
                || full == "System.Guid"
            )
            {
                return true;
            }
        }

        return underlying is IArrayTypeSymbol array
            && array.ElementType.SpecialType == SpecialType.System_Byte
            && array.Rank == 1;
    }

    private static ITypeSymbol? CollectionElementType(ITypeSymbol? type) =>
        type switch
        {
            IArrayTypeSymbol array => array.ElementType,
            INamedTypeSymbol named when named.TypeArguments.Length == 1 => named.TypeArguments[0],
            _ => null,
        };

    private static bool IsCollectionType(ITypeSymbol type)
    {
        if (type.SpecialType == SpecialType.System_String)
        {
            return false;
        }

        if (
            type is IArrayTypeSymbol array
            && array.ElementType.SpecialType == SpecialType.System_Byte
            && array.Rank == 1
        )
        {
            return false;
        }

        return type.AllInterfaces.Any(static iface =>
            iface.OriginalDefinition.SpecialType == SpecialType.System_Collections_IEnumerable
        );
    }

    // Exact-type parity with the runtime plan check: reference-type nullable
    // annotations are ignored by the comparer, but Nullable<T> value types
    // never match their underlying type (int? versus int reports SPF033).
    private static bool SameType(ITypeSymbol left, ITypeSymbol right) =>
        SymbolEqualityComparer.Default.Equals(left, right);

    private static StringBuilder AppendIndent(StringBuilder code, int indent)
    {
        for (var index = 0; index < indent; index++)
        {
            code.Append("    ");
        }

        return code;
    }

    // A valid model property may spell a reserved or contextual keyword
    // (@event): the symbol name needs an escape for member access emission.
    internal static string EscapeIdentifier(string name) =>
        SyntaxFacts.GetKeywordKind(name) != SyntaxKind.None
        || SyntaxFacts.GetContextualKeywordKind(name) != SyntaxKind.None
            ? "@" + name
            : name;
}
