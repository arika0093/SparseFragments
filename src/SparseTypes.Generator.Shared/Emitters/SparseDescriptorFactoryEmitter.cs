using System.Collections.Immutable;
using System.Linq;
using System.Text.RegularExpressions;
using System.Threading;

namespace SparseTypes.Generator.Shared;

/// <summary>Builds the relocated per-model descriptor factory.</summary>
/// <remarks>Reuses the existing descriptor emitters for the graph body.</remarks>
internal static class SparseDescriptorFactoryEmitter
{
    /// <summary>Builds the descriptor-factory additional source.</summary>
    /// <param name="model">Owning model.</param>
    /// <param name="members">Analyzed members.</param>
    /// <param name="config">Owning generator configuration.</param>
    /// <param name="cancellationToken">Cooperative cancellation.</param>
    /// <param name="runtimeNamespace">Runtime helper namespace.</param>
    /// <returns>Additional source with a distinct hint.</returns>
    public static SparseGeneratedSource BuildSource(
        SparseModelInfo model,
        ImmutableArray<SparseMemberModel> members,
        SparseGeneratorConfig config,
        CancellationToken cancellationToken,
        string runtimeNamespace
    )
    {
        var dialect =
            config.DescriptorDialect
            ?? throw new System.ArgumentException(
                "A descriptor dialect is required.",
                nameof(config)
            );
        using var innerBuilder = new SharedIndentedBuilder(cancellationToken);
        SparseObservableDescriptorEmitter.Append(
            innerBuilder,
            model.ModelTypeName,
            members,
            runtimeNamespace,
            dialect
        );
        var legacy = innerBuilder.ToString();
        // UI types nest in the model again: child observable references stay
        // model-nested, so only attribute-array bridges still rewrite.
        var relocated = SparseModelImplementationEmitter.RelocateAttributeBridges(
            legacy,
            model.ModelTypeName,
            members,
            cancellationToken
        );
        var body = RewriteReceiver(relocated, cancellationToken);
        // Legacy emits "internal IDescriptorSet
        // __SparseGetDescriptors_<hash>(pathType pathPrefix) {... }".
        body = Regex.Replace(
            body,
            @"internal\s+\S+\s+__SparseGetDescriptors_[0-9A-F]{8}\s*\(\s*\S+\s+pathPrefix\s*\)",
            "internal static "
                + dialect.DescriptorSetInterface
                + " Create("
                + ObservableParam(model, members, config, cancellationToken)
                + " observable, "
                + dialect.EffectivePathType(runtimeNamespace)
                + " pathPrefix)",
            RegexOptions.None,
            System.TimeSpan.FromSeconds(1)
        );
        var family = config.EffectiveFamilyNames;
        var observableSimple = SparseObservableEmitter.ObservableTypeName(members, family);
        using var code = new SharedIndentedBuilder(cancellationToken);
        code.AppendLine("// <auto-generated />");
        code.AppendLine("#nullable enable");
        var root =
            SparseGeneratedPlacement.TryGetImplementationNamespace(config)
            ?? throw new System.ArgumentException(
                "An implementation namespace is required.",
                nameof(config)
            );
        var container = SparseGeneratedPlacement.GetImplementationContainer(
            model,
            cancellationToken
        );
        var accessibility = model.IsPublic ? "public" : "internal";
        code.Append("namespace ").Append(root).AppendLine();
        code.AppendLine("{");
        // EditorBrowsable(Never) stays on the operation-container partial;
        // see SparseModelImplementationEmitter for the duplicate-attribute note.
        code.AppendLineAt(1, "/// <summary>Live descriptor bindings for one model.</summary>");
        code.AppendLineAt(1, accessibility + " partial class " + container);
        code.AppendLineAt(1, "{");
        code.AppendLineAt(
            2,
            "/// <summary>Descriptor factory bound to the owning observable.</summary>"
        );
        code.AppendLineAt(2, "internal static class DescriptorFactory");
        code.AppendLineAt(2, "{");
        code.Append(body);
        code.AppendLineAt(2, "}");
        code.AppendLineAt(1, "}");
        code.AppendLine("}");
        // Fix indentation: legacy body used indent 2/3/4 for nested Observable;
        // inside "namespace/container/factory" it needs one extra level.
        _ = observableSimple;
        var source = code.ToString();
        return new SparseGeneratedSource(
            SparseGeneratedPlacement.DescriptorFactoryHintName(model, cancellationToken),
            source
        );
    }

    private static string ObservableParam(
        SparseModelInfo model,
        ImmutableArray<SparseMemberModel> members,
        SparseGeneratorConfig config,
        CancellationToken cancellationToken
    )
    {
        var family = config.EffectiveFamilyNames;
        var simple = SparseObservableEmitter.ObservableTypeName(members, family);
        return SparseGeneratedPlacement.GetObservableReference(
            model,
            simple,
            config,
            cancellationToken
        );
    }

    /// <summary>Rebinds instance access from <c>this</c> to the factory parameter.</summary>
    /// <param name="source">Descriptor body emitted against the observable.</param>
    /// <param name="cancellationToken">Cooperative cancellation.</param>
    /// <returns>The body bound to the <c>observable</c> parameter.</returns>
    internal static string RewriteReceiver(string source, CancellationToken cancellationToken)
    {
        // Rewrite instance references to the factory parameter, longest names
        // first; skip literals and comments to preserve their contents.
        source = SparseCodeRewrite.ReplaceOutsideLiteralsAndComments(
            source,
            "this.",
            "observable.",
            cancellationToken
        );
        source = SparseCodeRewrite.ReplaceOutsideLiteralsAndComments(
            source,
            "__onRawModelAccess",
            "observable.__onRawModelAccess",
            cancellationToken
        );
        source = SparseCodeRewrite.ReplaceOutsideLiteralsAndComments(
            source,
            "__onChanged",
            "observable.__onChanged",
            cancellationToken
        );
        source = SparseCodeRewrite.ReplaceOutsideLiteralsAndComments(
            source,
            "__Raise(",
            "observable.__Raise(",
            cancellationToken
        );
        source = SparseCodeRewrite.ReplaceOutsideLiteralsAndComments(
            source,
            "__model.",
            "observable.__model.",
            cancellationToken
        );
        return source;
    }
}
