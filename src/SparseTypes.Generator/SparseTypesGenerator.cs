            SparseTypesDiagnosticIds.InvalidRebasePolicy => InvalidRebasePolicy,
            SparseTypesDiagnosticIds.InvalidComparisonStrategy => InvalidComparisonStrategy,
            SparseTypesDiagnosticIds.UnsupportedMerge => UnsupportedMerge,
            SparseTypesDiagnosticIds.UnsupportedRequired => UnsupportedRequired,
            SparseTypesDiagnosticIds.UnsupportedStructural => UnsupportedStructural,
            SparseTypesDiagnosticIds.UnsupportedClone => UnsupportedClone,
            SparseTypesDiagnosticIds.GeneratedNameCollision => GeneratedNameCollision,
